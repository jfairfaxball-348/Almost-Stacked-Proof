#!/usr/bin/env python3
"""S017: generate the G9 losing layers (STACK and CLEAR) as Lean certificate data.

The data is UNTRUSTED input to the Lean kernel checker (formal/AlmostStacked/Checker.lean):
soundness of the formal result does not depend on this script.  Configurations are encoded
as code(c) = sum_i c_i * 32^i.  Each layer is emitted as a balanced binary search tree.

usage: s017_gen_layers.py OUTDIR [--bench]
"""
import itertools, sys, os

E = [(0, 3), (0, 5), (0, 6), (1, 4), (1, 7), (1, 8), (2, 6), (2, 8), (3, 5), (3, 6), (4, 7), (4, 8), (5, 7), (6, 8)]
ADJ = E + [(b, a) for a, b in E]
N = 9
B = 32


def code(c):
    return sum(x * B ** i for i, x in enumerate(c))


def succs(c):
    for u, v in ADJ:
        if c[u] >= 2:
            d = list(c); d[u] -= 2; d[v] += 1
            yield tuple(d)


def layers(mode, top):
    good = (lambda c: sum(1 for x in c if x) == 1) if mode == 'stack' else (lambda c: sum(c) == 1)
    lose = {1: set()}
    for t in range(2, top + 1):
        cand = set()
        if t <= N:
            for s in itertools.combinations(range(N), t):
                cand.add(tuple(1 if i in s else 0 for i in range(N)))
        for s in lose[t - 1]:
            for u, v in ADJ:
                if s[v] >= 1:
                    c = list(s); c[u] += 2; c[v] -= 1
                    cand.add(tuple(c))
        L = set()
        for c in cand:
            if good(c):
                continue
            if all(d in lose[t - 1] for d in succs(c)):
                L.add(c)
        lose[t] = L
    return lose


def tree(keys):
    """balanced BST term over sorted keys, as a list of tokens"""
    if not keys:
        return ['.nil']
    m = len(keys) // 2
    return ['(.node'] + tree(keys[:m]) + [str(keys[m])] + tree(keys[m + 1:]) + [')']


def emit(tokens, width=100):
    lines, cur = [], '  '
    for tok in tokens:
        if len(cur) + len(tok) + 1 > width:
            lines.append(cur.rstrip()); cur = '    '
        cur += tok + ' '
    lines.append(cur.rstrip())
    return '\n'.join(lines)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for mode in ['stack', 'clear']:
        lose = layers(mode, 15)
        counts = [len(lose[t]) for t in range(1, 16)]
        print(mode, counts)
        Mode = mode.capitalize()
        for t in range(2, 16):
            keys = sorted(code(c) for c in lose[t])
            name = f'G9{Mode}{t}'
            path = os.path.join(out, f'{name}.lean')
            assert len(emit(tree(keys)).splitlines()) < 9000
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write('module\n\npublic import AlmostStacked.KTree\n\n')
                f.write(f'/-! Untrusted certificate data: the claimed {mode.upper()} losing layer of mass {t} on G9\n')
                f.write(f'({len(keys)} configurations, code = sum c_i 32^i), generated by tools/s017_gen_layers.py. -/\n\n')
                f.write('@[expose] public section\n\nnamespace AlmostStacked.Data\n\n')
                f.write(f'set_option maxRecDepth 100000 in\n/-- claimed {mode} losers of mass {t} -/\ndef {name} : KTree :=\n')
                f.write(emit(tree(keys)) + '\n\nend AlmostStacked.Data\n')


if __name__ == '__main__':
    main()


def emit_checks(root):
    """Per-layer kernel-check modules and the chaining modules (formal/AlmostStacked/G9)."""
    d = os.path.join(root, 'G9')
    os.makedirs(d, exist_ok=True)
    for mode, good, Pg in [('stack', 'goodStack 9', 'IsStacked'), ('clear', 'goodClear 9', '(fun d => size d = 1)')]:
        Mode = mode.capitalize()
        for t in range(2, 16):
            prev = 'KTree.nil' if t == 2 else f'Data.G9{Mode}{t-1}'
            imps = ['AlmostStacked.G9.Graph'] + ([] if t == 2 else [f'AlmostStacked.Data.G9{Mode}{t-1}']) + [f'AlmostStacked.Data.G9{Mode}{t}']
            with open(os.path.join(d, f'Check{Mode}{t}.lean'), 'w', encoding='utf-8', newline='\n') as f:
                f.write('module\n\n' + ''.join(f'public import {m}\n' for m in imps))
                f.write(f'\n/-! Kernel evaluation of the {mode.upper()} layer check for mass {t} on G9 (generated by tools/s017_gen_layers.py). -/\n\n')
                f.write('@[expose] public section\n\nnamespace AlmostStacked.G9Data\n\n')
                f.write(f'theorem {mode}_check_{t} :\n    layerB 9 g9Adj ({good}) {t} {prev} Data.G9{Mode}{t} = true := by\n  decide +kernel\n\nend AlmostStacked.G9Data\n')
        with open(os.path.join(d, f'{Mode}Layers.lean'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('module\n\n' + ''.join(f'public import AlmostStacked.G9.Check{Mode}{t}\n' for t in range(2, 16)))
            f.write(f'\n/-! The exact {mode.upper()} losing layers of G9 for masses 1..15 (generated by tools/s017_gen_layers.py). -/\n\n')
            f.write('@[expose] public section\n\nnamespace AlmostStacked.G9Data\n\n')
            f.write(f'theorem {mode}_layer_1 : ∀ c : Fin 9 → ℕ, size c = 1 →\n    (KTree.nil.Contains (enc c) ↔ ¬ Wins G9 {Pg} c) :=\n')
            f.write('  layer_one ' + ('(fun _ h => isStacked_of_size_one h)' if mode == 'stack' else '(fun _ h => h)') + '\n\n')
            for t in range(2, 16):
                prev = 'KTree.nil' if t == 2 else f'Data.G9{Mode}{t-1}'
                po = '(KTree.ordered_nil _ _)' if t == 2 else f'(by have h := {mode}_check_{t-1}; simp only [layerB, Bool.and_eq_true] at h; exact h.1)'
                f.write(f'theorem {mode}_layer_{t} : ∀ c : Fin 9 → ℕ, size c = {t} →\n    ((Data.G9{Mode}{t}).Contains (enc c) ↔ ¬ Wins G9 {Pg} c) :=\n')
                f.write(f'  layer_step setup ({good.split()[0]}_spec 9) (by norm_num) (by norm_num) {po} {mode}_layer_{t-1} {mode}_check_{t}\n\n')
            f.write('end AlmostStacked.G9Data\n')


if __name__ == '__main__' and len(sys.argv) > 2 and sys.argv[2] == '--checks':
    emit_checks(os.path.dirname(os.path.normpath(sys.argv[1])))
