#!/usr/bin/env python3
"""CAM-S003-01 graph catalogue: named labeled graphs and a self-generated small atlas.

Atlas: all simple graphs on n vertices up to isomorphism are generated by extending
every graph on n-1 vertices by one new vertex with every possible neighbourhood
(every n-vertex graph arises this way by deleting its last vertex), and reduced by
a canonical form = lexicographically least edge bitmask over all relabelings that
list vertices in non-decreasing degree order (an isomorphism-invariant set of
relabelings, hence a sound canonical form).  Counts are asserted against the known
sequences (OEIS A000088 all graphs, A001349 connected graphs).
"""
import itertools

KNOWN_ALL = {1: 1, 2: 2, 3: 4, 4: 11, 5: 34, 6: 156, 7: 1044, 8: 12346}
KNOWN_CONNECTED = {1: 1, 2: 1, 3: 2, 4: 6, 5: 21, 6: 112, 7: 853, 8: 11117}


def cycle(n):
    return [(i, (i + 1) % n) for i in range(n)]


def named():
    g = {}
    g['C6'] = (6, cycle(6))
    g['C7'] = (7, cycle(7))
    g['C8'] = (8, cycle(8))
    g['C8_chord_04'] = (8, cycle(8) + [(0, 4)])
    g['C8_triangle_chords'] = (8, cycle(8) + [(0, 2), (4, 6)])
    g['triangular_ladder'] = (8, [(0, 1), (1, 2), (2, 0), (3, 4), (4, 5), (5, 3), (2, 3), (6, 0), (7, 5)])
    g['K2_6'] = (8, [(i, j) for i in range(2) for j in range(2, 8)])
    g['W8'] = (8, [(0, i) for i in range(1, 8)] + [(i, i % 7 + 1) for i in range(1, 8)])
    g['Petersen'] = (10, [(i, (i + 1) % 5) for i in range(5)] + [(i, i + 5) for i in range(5)]
                     + [(5 + i, 5 + (i + 2) % 5) for i in range(5)])
    g['W9'] = (9, [(0, i) for i in range(1, 9)] + [(i, i % 8 + 1) for i in range(1, 9)])
    g['C9_chord_04'] = (9, cycle(9) + [(0, 4)])
    return g


def edge_string(edges):
    return ','.join(f'{a}-{b}' for a, b in sorted({tuple(sorted(e)) for e in edges}))


def _canon(n, edges):
    deg = [0] * n
    for a, b in edges:
        deg[a] += 1; deg[b] += 1
    classes = {}
    for v in range(n):
        classes.setdefault(deg[v], []).append(v)
    blocks = [classes[d] for d in sorted(classes)]
    pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
    bitpos = {p: k for k, p in enumerate(pairs)}
    best = None
    for parts in itertools.product(*(itertools.permutations(b) for b in blocks)):
        order = [v for part in parts for v in part]      # new label k -> old vertex order[k]
        newlab = [0] * n
        for k, v in enumerate(order):
            newlab[v] = k
        m = 0
        for a, b in edges:
            x, y = sorted((newlab[a], newlab[b]))
            m |= 1 << bitpos[(x, y)]
        if best is None or m < best:
            best = m
    return best, pairs


def all_graphs(n):
    """Return list of edge lists, one per isomorphism class of graphs on n vertices."""
    if n == 1:
        return [[]]
    out = {}
    for edges in all_graphs(n - 1):
        for mask in range(1 << (n - 1)):
            e = list(edges) + [(i, n - 1) for i in range(n - 1) if mask >> i & 1]
            key, pairs = _canon(n, e)
            if key not in out:
                out[key] = [pairs[k] for k in range(len(pairs)) if key >> k & 1]
    res = [out[k] for k in sorted(out)]
    assert len(res) == KNOWN_ALL[n], (n, len(res))
    return res


def connected(n, edges):
    adj = {v: set() for v in range(n)}
    for a, b in edges:
        adj[a].add(b); adj[b].add(a)
    seen, stack = {0}, [0]
    while stack:
        u = stack.pop()
        for w in adj[u] - seen:
            seen.add(w); stack.append(w)
    return len(seen) == n


def bipartite(n, edges):
    adj = {v: [] for v in range(n)}
    for a, b in edges:
        adj[a].append(b); adj[b].append(a)
    col = {}
    for s in range(n):
        if s in col:
            continue
        col[s] = 0; stack = [s]
        while stack:
            u = stack.pop()
            for w in adj[u]:
                if w not in col:
                    col[w] = 1 - col[u]; stack.append(w)
                elif col[w] == col[u]:
                    return False
    return True


def connected_atlas(n):
    res = [e for e in all_graphs(n) if connected(n, e)]
    assert len(res) == KNOWN_CONNECTED[n], (n, len(res))
    return res


def trees(n):
    return [e for e in connected_atlas(n) if len(e) == n - 1]


KNOWN_TREES = {1: 1, 2: 1, 3: 1, 4: 2, 5: 3, 6: 6, 7: 11, 8: 23, 9: 47, 10: 106, 11: 235, 12: 551}


def _tree_code(n, edges):
    """AHU canonical string of an unrooted tree, rooted at its centre(s)."""
    adj = {v: [] for v in range(n)}
    for a, b in edges:
        adj[a].append(b); adj[b].append(a)
    deg = {v: len(adj[v]) for v in range(n)}
    layer = [v for v in range(n) if deg[v] <= 1]
    left = n
    while left > 2:
        left -= len(layer)
        nxt = []
        for v in layer:
            for w in adj[v]:
                deg[w] -= 1
                if deg[w] == 1:
                    nxt.append(w)
            deg[v] = 0
        layer = nxt
    def enc(v, p):
        return '(' + ''.join(sorted(enc(w, v) for w in adj[v] if w != p)) + ')'
    return min(enc(c, -1) for c in layer)


def nonisomorphic_trees(n):
    """Trees on n vertices: extend each tree on n-1 vertices by a leaf at every vertex; dedupe by AHU code."""
    if n == 1:
        return [[]]
    out = {}
    for edges in nonisomorphic_trees(n - 1):
        for v in range(n - 1):
            e = list(edges) + [(v, n - 1)]
            out.setdefault(_tree_code(n, e), e)
    res = [out[k] for k in sorted(out)]
    assert len(res) == KNOWN_TREES[n], (n, len(res))
    return res


